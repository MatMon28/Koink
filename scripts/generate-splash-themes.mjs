/*
 * Writes android/app/src/main/res/values/splash_themes.xml: one launch-screen style per app
 * background colour.
 *
 *   npm run android:splash
 *
 * Android's system launch screen takes its colour from a *style*, and a style cannot be built at
 * run time. So the app ships one tiny style for every background it can have (Classic and five
 * style presets in three modes, plus ten Mono colours in three modes) and, on Android 13+, picks
 * the right one with setSplashScreenTheme (LaunchBackground.java). The names are
 * `Splash_<hex without #>`, so the web side only has to send the hex of the current --bg.
 *
 * Run it again whenever a --bg in src/index.css or src/styles/presets.css changes, or the Mono
 * palette in src/lib/themes.ts. `npm run android:prepare` checks that the file is up to date.
 * See docs/launch-intro.md.
 */
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const OUT = 'android/app/src/main/res/values/splash_themes.xml';
const MODES = ['light', 'lite-dark', 'dark'];
const colours = new Map(); // hex -> what uses it

const add = (hex, label) => {
  const key = hex.toLowerCase();
  if (!/^#[0-9a-f]{6}$/.test(key)) throw new Error(`Unexpected colour ${hex} for ${label}`);
  if (!colours.has(key)) colours.set(key, label);
};

/** The --bg of the first block with exactly this selector that sets one. */
function bgOf(css, selector, label) {
  for (const match of css.matchAll(new RegExp(`^${selector}\\s*\\{([^}]*)\\}`, 'gm'))) {
    const bg = match[1].match(/--bg:\s*(#[0-9a-fA-F]{6})/);
    if (bg) return add(bg[1], label);
  }
  throw new Error(`No --bg found for ${label}`);
}

// Classic: :root is Light, then the two dark modes.
const base = await readFile(`${root}src/index.css`, 'utf8');
bgOf(base, ':root', 'classic light');
bgOf(base, '\\[data-theme="lite-dark"\\]', 'classic lite-dark');
bgOf(base, '\\[data-theme="dark"\\]', 'classic dark');

const presets = await readFile(`${root}src/styles/presets.css`, 'utf8');
for (const style of ['angular', 'aurora', 'pop', 'playful', 'minimal']) {
  for (const mode of MODES) bgOf(presets, `html\\[data-style="${style}"\\]\\[data-theme="${mode}"\\]`, `${style} ${mode}`);
}

// Mono: the background depends on the chosen colour, computed by the app's own palette generator.
const bundled = await build({
  stdin: { contents: "export { getMonoVariables, MONO_HUES } from './src/lib/themes.ts';", resolveDir: root, loader: 'ts' },
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  logLevel: 'silent',
});
const themes = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
for (const hue of themes.MONO_HUES) {
  for (const mode of MODES) add(themes.getMonoVariables(hue.hex, mode)['--bg'], `mono ${hue.id} ${mode}`);
}

const rows = [...colours].map(([hex, label]) =>
  `    <!-- ${label} -->\n    <style name="Splash_${hex.slice(1)}" parent="AppTheme.NoActionBarLaunch">\n        <item name="windowSplashScreenBackground">${hex}</item>\n    </style>`);
const xml = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by scripts/generate-splash-themes.mjs (do not edit by hand): one launch-screen style per
  app background colour, chosen at run time by LaunchBackground.java (Android 13+). ${colours.size} colours.
-->
<resources>
${rows.join('\n')}
</resources>
`;

if (process.argv.includes('--check')) {
  const current = await readFile(root + OUT, 'utf8').catch(() => '');
  if (current !== xml) {
    console.error(`${OUT} is out of date. Run: npm run android:splash`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${colours.size} colours).`);
} else {
  await writeFile(root + OUT, xml);
  console.log(`Wrote ${colours.size} launch-screen styles to ${OUT}.`);
}
